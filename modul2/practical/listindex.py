# Python program to access elements at different index positions

my_list = [10, "Python", 3.14, True, "Programming"]

print("List:", my_list)

# Accessing elements using index positions
print("Element at index 0:", my_list[0])
print("Element at index 1:", my_list[1])
print("Element at index 2:", my_list[2])
print("Element at index 3:", my_list[3])
print("Element at index 4:", my_list[4])

# Accessing elements using negative indexing
print("Last element:", my_list[-1])
print("Second last element:", my_list[-2])